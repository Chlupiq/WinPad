#!/usr/bin/env python3
"""Turns the .text section of an x86-64 ELF object into a C header.

The probe embeds the guest as raw bytes, so the object must not need any
relocation and _start must be at offset 0.

Usage: elf2h.py GUEST.o GUEST.h
"""
import struct
import sys


def text_section(data):
    if data[:4] != b"\x7fELF" or data[4] != 2 or data[5] != 1:
        sys.exit("not a little-endian ELF64 object")
    shoff, = struct.unpack_from("<Q", data, 0x28)
    shentsize, shnum, shstrndx = struct.unpack_from("<HHH", data, 0x3A)
    sections = [struct.unpack_from("<IIQQQQIIQQ", data, shoff + i * shentsize) for i in range(shnum)]
    names_off = sections[shstrndx][4]

    def name(sec):
        start = names_off + sec[0]
        return data[start:data.index(b"\0", start)].decode()

    text = None
    for sec in sections:
        sh_type = sec[1]
        if sh_type in (4, 9):  # SHT_RELA, SHT_REL
            sys.exit(f"guest needs relocations ({name(sec)}); it must be position independent")
        if name(sec) == ".text":
            text = data[sec[4]:sec[4] + sec[5]]
    if text is None:
        sys.exit("no .text section")
    return text


def main():
    if len(sys.argv) != 3:
        sys.exit(__doc__)
    code = text_section(open(sys.argv[1], "rb").read())
    lines = [", ".join(f"0x{b:02x}" for b in code[i:i + 12]) for i in range(0, len(code), 12)]
    with open(sys.argv[2], "w") as out:
        out.write("// Generated by elf2h.py from guest.S\n#pragma once\n\n")
        out.write("static const unsigned char GuestCode[] = {\n  " + ",\n  ".join(lines) + "\n};\n")


if __name__ == "__main__":
    main()
